const profile = (displayName, active = false) => ({displayName,active,publicTitle:'Panelista',bio:'Acerca de ' + displayName,websiteUrl:'https://example.com'});
async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'deck-speakers-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const notifications = [];
  const options = {root,assertDeck:async id => { if (!['deck-a','deck-b'].includes(id)) throw new DeckSpeakerError('DECK_NOT_FOUND','Deck no encontrado.',404); },onChange:(...args) => notifications.push(args)};
  return {root,options,notifications,store:new DeckSpeakersStore(options)};
}
test('Deck profiles persist across restart, support arbitrary counts and preserve manual order', async t => {
  const {store,options,notifications} = await fixture(t);
  let config = await store.setEnabled('deck-a',{enabled:true,expectedRevision:0});
  for (let i=0;i<13;i++) config = await store.save('deck-a',null,{...profile('Ponente ' + i,i % 2 === 0),expectedRevision:config.revision});
  const ids = config.profiles.map(p=>p.id).reverse();
  config = await store.reorder('deck-a',{profileIds:ids,expectedRevision:config.revision});
  const restored = await new DeckSpeakersStore(options).read('deck-a');
  assert.deepEqual(restored.profiles.map(p=>p.id),ids);
  assert.equal(restored.revision,15);
  const dto = store.public(restored);
  assert.deepEqual(dto.profiles.map(p=>p.displayName),['Ponente 12','Ponente 10','Ponente 8','Ponente 6','Ponente 4','Ponente 2','Ponente 0']);
  assert.equal(dto.profile.id,ids[0]);
  assert.equal(JSON.stringify(dto).includes('"active"'),false);
  assert.equal(notifications.length,15);
  assert.deepEqual(await store.read('deck-b'),{schema:1,deckId:'deck-b',enabled:false,revision:0,profiles:[]});
});
test('All profiles off hides the multi-profile launcher without falling back to personal data', async t => {
  const {store} = await fixture(t);
  let config = await store.save('deck-a',null,{...profile('Ana',true),expectedRevision:0});
  config = await store.setEnabled('deck-a',{enabled:true,expectedRevision:config.revision});
  const id=config.profiles[0].id;
  config = await store.setActive('deck-a',id,{active:false,expectedRevision:config.revision});
  assert.equal(store.public(await store.read('deck-a')).available,false);
  assert.equal(config.profiles[0].displayName,'Ana');
  assert.equal(config.profiles.length,1);
  config = await store.setActive('deck-a',id,{active:true,expectedRevision:config.revision});
  assert.equal(store.public(await store.read('deck-a')).profiles[0].displayName,'Ana');
});
test('Concurrent editors reject stale writes and invalid orders without losing committed content', async t => {
  const {store,notifications} = await fixture(t);
  const outcomes = await Promise.allSettled([store.save('deck-a',null,{...profile('Uno'),expectedRevision:0}),store.save('deck-a',null,{...profile('Dos'),expectedRevision:0})]);
  assert.equal(outcomes.filter(p=>p.status==='fulfilled').length,1);
  assert.equal(outcomes.find(p=>p.status==='rejected').reason.statusCode,409);
  await assert.rejects(store.reorder('deck-a',{expectedRevision:1,profileIds:[]}),{code:'INVALID_ORDER'});
  assert.equal((await store.read('deck-a')).profiles.length,1); assert.equal(notifications.length,1);
});
test('Draft, disabled and replaced photos remain private; owner previews work', async t => {
  const {store} = await fixture(t);
  let config = await store.save('deck-a',null,{...profile('Foto'),expectedRevision:0}), id=config.profiles[0].id;
  config = await store.setPhoto('deck-a',id,config.revision,Buffer.from('fixture'),'.png');
  const old = (await store.read('deck-a')).profiles[0].photoKey;
  assert.equal(await fs.readFile(await store.photo('deck-a',id,old,true),'utf8'),'fixture');
  await assert.rejects(store.photo('deck-a',id,old),{statusCode:404});
  config = await store.setEnabled('deck-a',{enabled:true,expectedRevision:config.revision});
  await assert.rejects(store.photo('deck-a',id,old),{statusCode:404});
  config = await store.setActive('deck-a',id,{active:true,expectedRevision:config.revision});
  assert.ok(await store.photo('deck-a',id,old));
  config = await store.setPhoto('deck-a',id,config.revision,Buffer.from('replacement'),'.webp');
  await assert.rejects(store.photo('deck-a',id,old),{statusCode:404});
  assert.match(config.profiles[0].photoUrl,/\/speakers\/.+\/photo\//);
  assert.match(store.public(await store.read('deck-a')).profiles[0].photoUrl,/\/speaker-photos\//);
  await store.removeDeck('deck-a');
  assert.equal((await store.read('deck-a')).revision,0);
});
