test('HTTP owner checks, CSRF and revisions protect profiles and drafts', async t => {
  const {request}=await httpFixture(t),base='/api/decks/deck-a/speakers';
  assert.equal((await request(base,{headers:{'x-test-account':''}})).status,401);
  assert.equal((await request(base,{headers:{'x-test-account':'stranger'}})).status,404);
  assert.equal((await request('/api/decks/deck-b/speakers')).status,404);
  assert.equal((await request(base,{method:'POST',headers:{Origin:'https://evil.example'},body:JSON.stringify({...profile('CSRF'),expectedRevision:0})})).status,403);
  let response=await request(base,{method:'POST',body:JSON.stringify({...profile('Borrador'),expectedRevision:0})});
  assert.equal(response.status,201); let config=await response.json();
  assert.equal((await (await request('/api/decks/deck-a/speaker-profile')).json()).profile.displayName,'Personal');
  response=await request(base+'/settings',{method:'PUT',body:JSON.stringify({enabled:true,expectedRevision:config.revision})}); config=await response.json();
  const dto=await (await request('/api/decks/deck-a/speaker-profile')).json();
  assert.equal(dto.mode,'multiple'); assert.equal(dto.available,false); assert.equal(dto.profile,null);
  assert.equal(JSON.stringify(dto).includes('Borrador'),false);
  response=await request(base+'/'+config.profiles[0].id+'/active',{method:'PUT',body:JSON.stringify({active:true,expectedRevision:config.revision})});
  assert.equal(response.status,200);
  response=await request(base+'/settings',{method:'PUT',body:JSON.stringify({enabled:false,expectedRevision:config.revision})}); assert.equal(response.status,409);
  response=await request('/api/decks/deck-a/speaker-profile'); assert.equal(response.headers.get('cache-control'),'no-store');
  assert.equal((await response.json()).profiles[0].displayName,'Borrador');
});
